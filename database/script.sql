CREATE TABLE CLIENTES (
    ID_CLIENTE  NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMBRE      VARCHAR2(100 BYTE) NOT NULL,
    APELLIDO    VARCHAR2(100 BYTE) NOT NULL,
    TELEFONO    VARCHAR2(15 BYTE)  NOT NULL,
    EMAIL       VARCHAR2(100 BYTE) NOT NULL,
    DIRECCION   VARCHAR2(200 BYTE),
    CONSTRAINT CLIENTES_PK PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT CLIENTES_EMAIL_UN UNIQUE (EMAIL)
);

CREATE TABLE VEHICULOS (
    ID_VEHICULO  NUMBER GENERATED ALWAYS AS IDENTITY,
    MARCA        VARCHAR2(100 BYTE) NOT NULL,
    MODELO       VARCHAR2(100 BYTE) NOT NULL,
    CAPACIDAD    NUMBER             NOT NULL,
    PRECIO_DIA   NUMBER(10,2)       NOT NULL,
    PLACA        VARCHAR2(20 BYTE)  NOT NULL,
    CONSTRAINT VEHICULOS_PK PRIMARY KEY (ID_VEHICULO),
    CONSTRAINT VEHICULOS_PLACA_UN UNIQUE (PLACA)
);

CREATE TABLE RESERVAS (
    ID_RESERVA          NUMBER GENERATED ALWAYS AS IDENTITY,
    ID_CLIENTE          NUMBER             NOT NULL,
    ID_VEHICULO         NUMBER             NOT NULL,
    NOMBRE_RESERVA      VARCHAR2(100 BYTE) NOT NULL,
    FECHA_RESERVA       DATE               NOT NULL,
    CANTIDAD_PASAJEROS  NUMBER             NOT NULL,
    CANTIDAD_DIAS       NUMBER             NOT NULL,
    ESTADO              VARCHAR2(20 BYTE),
    TOTAL_PAGO          NUMBER(8,2),
    CONSTRAINT RESERVAS_PK PRIMARY KEY (ID_RESERVA),
    CONSTRAINT FK_RESERVAS_CLIENTES  FOREIGN KEY (ID_CLIENTE)  REFERENCES CLIENTES (ID_CLIENTE),
    CONSTRAINT FK_RESERVAS_VEHICULOS FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULOS (ID_VEHICULO)
);

